"""Write docs/appendix-a-config.md from the source of `PipelineConfig` and `Result`, so the reference cannot drift from the code.

  python -m tools.gen_config_doc            # rewrites docs/appendix-a-config.md
  python -m tools.gen_config_doc --check    # exit 1 if the file is out of date (used by the tests)
"""
from __future__ import annotations

import argparse
import dataclasses
import inspect
import os
import re
import sys

from docangle import PipelineConfig, Result

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "docs", "appendix-a-config.md")
FIELD = re.compile(r"^    (\w+): ([^=#]+?)(?: = (.*?))?(?:\s+# (.*))?$")


def parse(cls):
    """[(section, name, type, default, comment)] from the class source: inline comments, continuation comments and '# Section' lines."""
    rows, section, last = [], "", None
    for line in inspect.getsource(cls).splitlines():
        m = re.match(r"^    # (.+)$", line)
        if m and not line.startswith("     "):
            section, last = m.group(1).strip(), None
            continue
        if re.match(r"^\s{20,}# ", line) and last is not None:
            rows[last][4] += " " + line.split("# ", 1)[1].strip()
            continue
        m = FIELD.match(line)
        if m and m.group(1) in {f.name for f in dataclasses.fields(cls)}:
            rows.append([section, m.group(1), m.group(2).strip(), (m.group(3) or "").strip(), (m.group(4) or "").strip()])
            last = len(rows) - 1
    return rows


def table(rows):
    out, section = [], None
    for sec, name, typ, default, comment in rows:
        if sec != section:
            out += ["", f"**{sec or 'General'}**", "", "| field | type | default | meaning |", "|---|---|---|---|"]
            section = sec
        out.append(f"| `{name}` | `{typ}` | `{default or '—'}` | {comment.replace('|', '/') or '—'} |")
    return "\n".join(out)


def render():
    return "\n".join([
        "# Appendix A: configuration and result reference",
        "",
        "*Generated by `python -m tools.gen_config_doc` from the source code; do not edit by hand.*",
        "",
        "`PipelineConfig` is a frozen dataclass: every constant of the pipeline lives in it, it is hashable, and it is stored with benchmark results. "
        "Defaults are the shipped behaviour; most options exist for the experiments of [chapter 11](11-decisions.md).",
        "",
        "## A.1 `PipelineConfig`",
        table(parse(PipelineConfig)),
        "",
        "## A.2 `Result`",
        "",
        "`Result.to_dict()` gives the same fields as a dictionary (the command line prints them with `--json`).",
        table(parse(Result)),
        "",
    ])


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        ok = os.path.exists(OUT) and open(OUT, encoding="utf-8").read() == text
        print("up to date" if ok else "OUT OF DATE: run python -m tools.gen_config_doc")
        return 0 if ok else 1
    open(OUT, "w", encoding="utf-8").write(text)
    print("wrote", OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
